#!/usr/bin/env node
/**
 * Regenerates the mapping table inside `apps/desktop/docs/cli-session-mapping.md`
 * from the source of truth at
 * `src/main/lib/cli-session/mapping-table.ts`.
 *
 * Run manually after editing MAPPING_TABLE:
 *   bun scripts/gen-mapping-docs.mjs
 *
 * CI check (recommended): after running this script, `git diff --exit-code
 * apps/desktop/docs/cli-session-mapping.md` should be clean. If the docs file
 * is out of sync the diff will fail.
 *
 * Implementation: rather than importing the TypeScript source (which would
 * require a transpile step in this lightweight script), we lightly parse the
 * source file for the MAPPING_TABLE literal. The format is constrained
 * enough that a regex-walking parser is the right amount of complexity.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = join(__dirname, '..', 'src', 'main', 'lib', 'cli-session', 'mapping-table.ts');
const DOC = join(__dirname, '..', 'docs', 'cli-session-mapping.md');
const BEGIN = '<!-- MAPPING:BEGIN — DO NOT EDIT: regenerated by scripts/gen-mapping-docs.mjs -->';
const END = '<!-- MAPPING:END -->';

const source = readFileSync(SRC, 'utf8');
const arrayStart = source.indexOf('export const MAPPING_TABLE');
if (arrayStart === -1) {
  console.error('MAPPING_TABLE not found in', SRC);
  process.exit(1);
}

// Pull the JSON-looking body between the first `[` AFTER the `=` and its
// matching `]`. The TS type annotation contains `MappingRow[]` which would
// otherwise be matched by a naive indexOf('[').
const eqPos = source.indexOf('=', arrayStart);
if (eqPos === -1) {
  console.error('Could not find `=` after MAPPING_TABLE');
  process.exit(1);
}
const bodyStart = source.indexOf('[', eqPos);
if (bodyStart === -1) {
  console.error('Could not find array body start');
  process.exit(1);
}
let depth = 0;
let i = bodyStart;
for (; i < source.length; i++) {
  const ch = source[i];
  if (ch === '[') depth++;
  else if (ch === ']') {
    depth--;
    if (depth === 0) {
      i++;
      break;
    }
  }
}
const literalText = source.slice(bodyStart, i);

// eval'ing arbitrary TS literal isn't safe in general, but this file is
// repo-controlled and only contains object/array literals (no function calls
// or side effects). Wrap in a function to scope. Strip `as` casts.
const cleaned = literalText.replace(/\s+as\s+SideEffectKind/g, '');
let rows;
try {
  rows = new Function(`return ${cleaned}`)();
} catch (err) {
  console.error('Failed to evaluate MAPPING_TABLE literal:', err);
  process.exit(1);
}

function fmtList(arr) {
  if (!Array.isArray(arr) || arr.length === 0) return '';
  return arr.map((s) => `\`${s}\``).join(', ');
}

function summarizeClaude(row) {
  const parts = [];
  if (row.claude.eventTypes?.length) parts.push(`event: ${fmtList(row.claude.eventTypes)}`);
  if (row.claude.contentTypes?.length) parts.push(`content[].type: ${fmtList(row.claude.contentTypes)}`);
  if (row.claude.toolNames?.length) parts.push(`tool_use.name: ${fmtList(row.claude.toolNames)}`);
  if (row.claude.notes) parts.push(`_${escapePipes(row.claude.notes)}_`);
  return parts.join('<br>') || '—';
}

function summarizeCodex(row) {
  const parts = [];
  if (row.codex.payloadTypes?.length) parts.push(`payload.type: ${fmtList(row.codex.payloadTypes)}`);
  if (row.codex.functionNames?.length) parts.push(`function_call.name: ${fmtList(row.codex.functionNames)}`);
  if (row.codex.notes) parts.push(`_${escapePipes(row.codex.notes)}_`);
  return parts.join('<br>') || '—';
}

function escapePipes(s) {
  return String(s).replace(/\|/g, '\\|');
}

const header =
  '| Renderer part type | Renderer component | Claude (event / content / tool) | Codex (payload / function) | Side effect | Description |\n' +
  '|---|---|---|---|---|---|\n';

const lines = rows.map((row) => {
  const partType = row.partType ? `\`${row.partType}\`` : '_(skip)_';
  const comp = row.rendererComponent ? row.rendererComponent : '—';
  const claude = summarizeClaude(row);
  const codex = summarizeCodex(row);
  const se = row.sideEffect ? `\`${row.sideEffect}\`` : '';
  const desc = escapePipes(row.description);
  return `| ${partType} | ${comp} | ${claude} | ${codex} | ${se} | ${desc} |`;
});

const table = header + lines.join('\n') + '\n';

const doc = readFileSync(DOC, 'utf8');
const beginIdx = doc.indexOf(BEGIN);
const endIdx = doc.indexOf(END);
if (beginIdx === -1 || endIdx === -1 || endIdx < beginIdx) {
  console.error(`Markers ${BEGIN} / ${END} not found in ${DOC}`);
  process.exit(1);
}
const before = doc.slice(0, beginIdx + BEGIN.length);
const after = doc.slice(endIdx);
const next = `${before}\n\n${table}\n${after}`;

if (next !== doc) {
  writeFileSync(DOC, next, 'utf8');
  console.log('Regenerated mapping table in', DOC);
} else {
  console.log('Mapping table already up to date.');
}
